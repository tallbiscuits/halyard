void test_real_slicer_file_binary() {
  // The full firmware's path: M28 B1, compressed. The printer's copy is the same bytes the
  // ASCII path writes, so sizes, the copy check and printing do not care which ran.
  FakeMarlin::Options o;
  o.binary = true;
  Rig r(o);
  store(r.lib, "Phone_Stand_02_PLA_2h17m.gcode", fixture("orca_phone_stand.gc"));
  r.ready();
  std::string res = r.hand_off("Phone_Stand_02_PLA_2h17m.gcode", false);
  assert_starts("OK: on the printer's card as PHONES~1.GCO", res);
  TEST_ASSERT_TRUE(r.m.files["PHONES~1.GCO"] == expected_on_printer(fixture("orca_phone_stand.gc")));
  bool binary = false;
  for (auto& e : r.events) binary |= e.find("binary, compressed") != std::string::npos;
  TEST_ASSERT_TRUE(binary);
  TEST_ASSERT_FALSE(r.m.binary_mode);
  assert_starts("OK: printing", r.hand_off("Phone_Stand_02_PLA_2h17m.gcode", true));
}

