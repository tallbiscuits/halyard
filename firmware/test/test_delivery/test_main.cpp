void test_library_stores_metadata_and_thumbnails() {
  Library lib(g_root);
  TEST_ASSERT_TRUE(lib.begin());
  store(lib, "Benchy v2.gcode", prusa_with_thumbnails());
  LibraryEntry e;
  TEST_ASSERT_TRUE(lib.get("Benchy v2.gcode", e));
  TEST_ASSERT_EQUAL(prusa_with_thumbnails().size(), e.size);
  TEST_ASSERT_EQUAL_STRING("PrusaSlicer", e.meta.slicer.c_str());
  TEST_ASSERT_EQUAL_STRING("2.8.1+linux-x64", e.meta.slicer_version.c_str());
  TEST_ASSERT_EQUAL_FLOAT(3723, e.meta.estimated_time);
  TEST_ASSERT_EQUAL_FLOAT(121, e.meta.filament_total);
  TEST_ASSERT_EQUAL_FLOAT(4.2, e.meta.filament_weight_total);
  TEST_ASSERT_EQUAL_FLOAT(12.35, e.meta.object_height);
  TEST_ASSERT_EQUAL_FLOAT(-1, e.meta.first_layer_extr_temp);
  // The QOI block is skipped, the broken PNG block dropped along with its file.
  TEST_ASSERT_EQUAL(2, e.meta.thumbnails.size());
  const Thumbnail& t = e.meta.thumbnails[1];
  TEST_ASSERT_EQUAL(220, t.width);
  TEST_ASSERT_EQUAL(124, t.height);
  TEST_ASSERT_EQUAL(kPng.size(), t.size);
  TEST_ASSERT_EQUAL_STRING(".thumbs/Benchy v2-220x124.png", t.relative_path.c_str());
  TEST_ASSERT_TRUE(read_all(g_root + "/" + t.relative_path) == kPng);
  TEST_ASSERT_TRUE(read_all(g_root + "/" + e.meta.thumbnails[0].relative_path) == kPng);
  TEST_ASSERT_FALSE(exists(g_root + "/.thumbs/Benchy v2-300x300.png"));

  // Survives a reload from its .meta file.
  Library again(g_root);
  LibraryEntry e2;
  TEST_ASSERT_TRUE(again.get("Benchy v2.gcode", e2));
  TEST_ASSERT_EQUAL_STRING(e.meta.serialize().c_str(), e2.meta.serialize().c_str());

  // Remove takes the thumbnails and metadata with it.
  TEST_ASSERT_TRUE(lib.remove("Benchy v2.gcode"));
  TEST_ASSERT_EQUAL(0, lib.names().size());
  TEST_ASSERT_FALSE(exists(g_root + "/" + t.relative_path));
  TEST_ASSERT_FALSE(exists(g_root + "/.meta/Benchy v2.gcode.meta"));
}

