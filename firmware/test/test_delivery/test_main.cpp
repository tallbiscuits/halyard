static void handoff_and_print(FakeMarlin::Options o) {
  Rig r(o);
  std::string data = harmless_job(3, 215, 60);
  store(r.lib, "Phone Stand v2.gcode", data);
  r.ready();
  std::string res = r.hand_off("Phone Stand v2.gcode", true);
  assert_starts("OK: printing Phone Stand v2.gcode (PHONES~1.GCO)", res);
  TEST_ASSERT_TRUE(r.m.files["PHONES~1.GCO"] == expected_on_printer(data));
  // Preheat before the transfer; the print is started with the 8.3 name.
  TEST_ASSERT_TRUE(r.index_of("M140 S60") >= 0);
  TEST_ASSERT_TRUE(r.index_of("M104 S215") >= 0);
  TEST_ASSERT_TRUE(r.index_of("M140 S60") < r.index_of("M28 PHONES~1.GCO"));
  TEST_ASSERT_TRUE(r.index_of("M23 PHONES~1.GCO") > r.index_of("M28 PHONES~1.GCO"));
  TEST_ASSERT_EQUAL(215, r.m.hotend_target);
  TEST_ASSERT_EQUAL(Job::Printing, r.printer.status().job);
  LibraryEntry e;
  TEST_ASSERT_TRUE(r.lib.get("Phone Stand v2.gcode", e));
  TEST_ASSERT_EQUAL_STRING("PHONES~1.GCO", e.printer_name.c_str());
  TEST_ASSERT_EQUAL(r.m.files["PHONES~1.GCO"].size(), e.printer_size);
  TEST_ASSERT_TRUE(r.run_until([&] { return r.printer.status().job == Job::Idle; }, 60000));
}

