// A firmware update restarts Halyard: refused during a copy to the printer (it would be
// lost), allowed otherwise, and a setting changed just before is saved first.
void test_restart_for_update() {
  {
    Rig r;
    r.svc.ws_open(1);
    r.ready();
    std::string why;
    TEST_ASSERT_TRUE(r.svc.can_restart(why));
    Form f;
    TEST_ASSERT_EQUAL(201, r.upload(false, f.type(), f.file("big.gcode", harmless_job(400)).done()).status);
    r.result(1, "printer.print.start", "{\"filename\":\"big.gcode\"}");
    TEST_ASSERT_TRUE(r.run_until([&] { return r.delivery.progress().bytes > 1000; }, 60000));
    TEST_ASSERT_FALSE(r.svc.can_restart(why));
    TEST_ASSERT_TRUE(why.find("copied") != std::string::npos);
    r.result(1, "printer.print.cancel");
    TEST_ASSERT_TRUE(r.run_until([&] { return !r.delivery.busy(); }, 30000));
    TEST_ASSERT_TRUE(r.svc.can_restart(why));
    r.result(1, "server.database.post_item",
             "{\"namespace\":\"mainsail\",\"key\":\"theme\",\"value\":\"light\"}");
    r.svc.reboot_soon();
    TEST_ASSERT_TRUE(r.run_until([&] { return r.rebooted; }, 1000));  // before the 2 s save
  }
  Rig r2;
  HttpResponse res;
  TEST_ASSERT_TRUE(r2.svc.http("GET", "/server/database/item", "namespace=mainsail&key=theme", "", res));
  TEST_ASSERT_EQUAL_STRING("light", parse(res.body)["result"]["value"]);
}

// Halyard restarts (an update) while the printer prints a file it handed off. The new
// Halyard finds the print running before M27 C has named the file: the job must still show
// under its library name, in print_stats and in the history.
void test_print_found_running_gets_its_name() {
  Rig r;
  r.svc.ws_open(1);
  r.ready();
  Form f;
  TEST_ASSERT_EQUAL(201, r.upload(false, f.type(), f.file("long job.gcode", harmless_job(120)).done()).status);
  r.result(1, "printer.print.start", "{\"filename\":\"long job.gcode\"}");
  TEST_ASSERT_TRUE(r.run_until([&] { return r.m.sd_printing; }, 60000));
  r.run_until([] { return false; }, 2000);

  Link l2(r.t);  // the restarted Halyard: new everything, same card and printer
  Printer p2(l2);
  Delivery d2(p2, r.lib);
  bool rebooted = false;
  Service s2(l2, p2, d2, r.lib, Rig::platform(&rebooted));
  s2.begin();
  p2.on_line = [&](const std::string& l) { s2.printer_line(l); };
  s2.ws_open(2);
  auto name = [&] {
    std::string q = s2.ws_message(2, "{\"jsonrpc\":\"2.0\",\"method\":\"printer.objects.query\",\"params\":"
                                     "{\"objects\":{\"print_stats\":[\"filename\"]}},\"id\":1}");
    return parse(q)["result"]["status"]["print_stats"]["filename"].as<std::string>();
  };
  bool named = false;
  for (uint32_t i = 0; i < 20000 && !named; i++) {
    p2.poll(r.now);
    d2.poll(r.now);
    s2.poll(r.now);
    r.m.tick(r.now);
    int conn;
    std::string text;
    while (s2.take(conn, text)) {}
    r.now++;
    if (i % 100 == 0) named = name() == "long job.gcode";
  }
  TEST_ASSERT_TRUE_MESSAGE(named, name().c_str());
  TEST_ASSERT_TRUE(r.m.sd_printing);
  std::string h = s2.ws_message(2, "{\"jsonrpc\":\"2.0\",\"method\":\"server.history.list\",\"params\":{},\"id\":2}");
  TEST_ASSERT_EQUAL_STRING("long job.gcode", parse(h)["result"]["jobs"][0]["filename"]);
}

void test_line_noise_stays_out_of_the_console() {
  // The GEEK's ROM boot log reaches the printer at every reset, and Marlin echoes it back.
  Rig r;
  r.svc.ws_open(1);
  r.svc.printer_line("echo:Unknown command: \"\xe6\xc6\x18\x06\xad\xb5\"");
  r.svc.printer_line("echo:Unknown command: \"M999x\"");
  r.svc.respond("from the printer: \xe6\x18 done");
  r.drain();
  JsonDocument store = r.result(1, "server.gcode_store");
  JsonArray a = store["result"]["gcode_store"];
  TEST_ASSERT_EQUAL(2, a.size());
  TEST_ASSERT_EQUAL_STRING("Unknown command: \"M999x\"", a[0]["message"]);
  TEST_ASSERT_EQUAL_STRING("from the printer: ?? done", a[1]["message"]);
  // Every frame sent is plain ASCII, so it is valid UTF-8 and valid JSON.
  for (auto& f : r.sent[1])
    for (unsigned char c : f) TEST_ASSERT_TRUE(c >= 0x20 && c < 0x7f);
}

