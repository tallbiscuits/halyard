// ---- Halyard's own: the hand-off's progress and the printer's card ---------------------

void test_handoff_progress_in_halyard_object() {
  Rig r;
  r.svc.ws_open(1);
  r.ready();
  Form f;
  TEST_ASSERT_EQUAL(201, r.upload(false, f.type(), f.file("copy me.gcode", with_thumbnail(harmless_job(300))).done()).status);
  r.result(1, "printer.objects.subscribe", "{\"objects\":{\"halyard\":null}}");
  uint32_t version = r.result(1, "printer.objects.query", "{\"objects\":{\"halyard\":null}}")
                         ["result"]["status"]["halyard"]["card_version"];
  // A copy without a print, as Mainsail's "copy to the printer's card" asks for it.
  r.result(1, "printer.card.copy", "{\"filename\":\"gcodes/copy me.gcode\"}");
  TEST_ASSERT_TRUE(r.run_until([&] { return r.delivery.progress().bytes > 2000; }, 60000));
  r.run_until([] { return false; }, 300);
  JsonDocument q = r.result(1, "printer.objects.query", "{\"objects\":{\"halyard\":null}}");
  JsonObject h = q["result"]["status"]["halyard"]["handoff"];
  TEST_ASSERT_EQUAL_STRING("uploading", h["state"]);
  TEST_ASSERT_EQUAL_STRING("copy me.gcode", h["filename"]);
  TEST_ASSERT_EQUAL_STRING("COPYME~1.GCO", h["printer_name"]);
  TEST_ASSERT_FALSE(h["print"].as<bool>());
  TEST_ASSERT_TRUE(h["bytes"].as<uint32_t>() > 2000 && h["bytes"].as<uint32_t>() < h["total"].as<uint32_t>());
  TEST_ASSERT_TRUE(h["elapsed"].as<double>() > 0);
  // Nothing prints, so the job stays as it was.
  q = r.result(1, "printer.objects.query", "{\"objects\":{\"print_stats\":[\"state\"]}}");
  TEST_ASSERT_EQUAL_STRING("standby", q["result"]["status"]["print_stats"]["state"]);
  // Another copy waits: one hand-off at a time.
  JsonDocument busy = r.call(1, "printer.card.copy", "{\"filename\":\"copy me.gcode\"}");
  TEST_ASSERT_EQUAL(409, busy["error"]["code"].as<int>());
  TEST_ASSERT_TRUE(r.run_until([&] { return !r.delivery.busy(); }, 120000));
  r.run_until([] { return false; }, 1000);  // the card is listed again
  // The subscription saw the progress rise, then the hand-off end and the card change.
  uint32_t last_bytes = 0;
  bool rose = false, idle = false, changed = false;
  for (auto& n : r.notes(1, "notify_status_update")) {
    JsonObject d = n["params"][0]["halyard"];
    if (d.isNull()) continue;
    if (d["handoff"]["state"] == "uploading") {
      uint32_t b = d["handoff"]["bytes"];
      rose |= b > last_bytes && last_bytes > 0;
      last_bytes = b;
    }
    idle |= d["handoff"]["state"] == "idle";
    changed |= !d["card_version"].isNull() && d["card_version"].as<uint32_t>() != version;
  }
  TEST_ASSERT_TRUE(rose);
  TEST_ASSERT_TRUE(idle);
  TEST_ASSERT_TRUE(changed);
  JsonDocument l = r.result(1, "printer.card.list", "{\"refresh\":false}");
  JsonArray files = l["result"]["files"];
  TEST_ASSERT_EQUAL(1, files.size());
  TEST_ASSERT_EQUAL_STRING("COPYME~1.GCO", files[0]["name"]);
  TEST_ASSERT_EQUAL_STRING("copy me.gcode", files[0]["library"]);
  TEST_ASSERT_TRUE(files[0]["current"].as<bool>());
  TEST_ASSERT_TRUE(files[0]["modified"].isNull());  // the printer's no-clock date, left out
  // The library file's metadata, as server.files.metadata has it, for a copy that is current.
  JsonObject meta = files[0]["metadata"];
  TEST_ASSERT_EQUAL_FLOAT(300, meta["estimated_time"].as<float>());
  TEST_ASSERT_EQUAL_STRING("PrusaSlicer", meta["slicer"]);
  TEST_ASSERT_EQUAL(1, meta["thumbnails"].size());
  TEST_ASSERT_TRUE(l["result"]["listed"].as<bool>());
  // A copy can be stopped like a print's copy; nothing was printing, so no job ends.
  Form f2;
  TEST_ASSERT_EQUAL(201, r.upload(false, f2.type(), f2.file("stop me.gcode", harmless_job(300)).done()).status);
  r.result(1, "printer.card.copy", "{\"filename\":\"stop me.gcode\"}");
  TEST_ASSERT_TRUE(r.run_until([&] { return r.delivery.progress().bytes > 2000; }, 60000));
  r.result(1, "printer.print.cancel");
  TEST_ASSERT_TRUE(r.run_until([&] { return !r.delivery.busy(); }, 30000));
  TEST_ASSERT_TRUE(r.console_has(1, "Copy of stop me.gcode cancelled"));
  q = r.result(1, "printer.objects.query", "{\"objects\":{\"print_stats\":[\"state\"]}}");
  TEST_ASSERT_EQUAL_STRING("standby", q["result"]["status"]["print_stats"]["state"]);
  TEST_ASSERT_EQUAL(0, r.count_executed("M24"));
}

