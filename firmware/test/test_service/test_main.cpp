void test_mainsail_in_the_update_manager() {
  std::string installed = "v2.19.0";
  Rig r;
  r.svc.ws_open(1);
  // Without the glue's hooks there is nothing to show.
  TEST_ASSERT_EQUAL(0, r.result(1, "machine.update.status")["result"]["version_info"].size());

  Platform p = Rig::platform(&r.rebooted);
  p.ui_version = [&] { return installed; };
  p.ui_release = "v2.19.0-halyard.1";  // what this firmware ships with (D13)
  Service svc(r.link, r.printer, r.delivery, r.lib, p);
  svc.ws_open(1);
  int checks = 0;
  std::vector<std::string> started;
  svc.on_update_check = [&] { checks++; };
  svc.on_update = [&](const std::string& n, std::string&) { started.push_back(n); return true; };
  auto call = [&](const std::string& method, const std::string& params) {
    std::string out = svc.ws_message(1, "{\"jsonrpc\":\"2.0\",\"method\":\"" + method +
                                           "\",\"params\":" + params + ",\"id\":7}");
    return parse(out);
  };
  auto notes = [&](const std::string& method) {
    std::vector<JsonDocument> out;
    int conn;
    std::string text;
    while (svc.take(conn, text))
      if (text.find("\"" + method + "\"") != std::string::npos) out.push_back(parse(text));
    return out;
  };
  JsonDocument info = call("server.info", "{}");  // Mainsail shows the panel for this component
  bool listed = false;
  for (JsonVariantConst c : info["result"]["components"].as<JsonArrayConst>()) listed |= c == "update_manager";
  TEST_ASSERT_TRUE(listed);
  JsonDocument st = call("machine.update.status", "{}");  // Mainsail's start-up: no check
  TEST_ASSERT_EQUAL(0, checks);
  JsonObject m = st["result"]["version_info"]["mainsail"];
  TEST_ASSERT_EQUAL_STRING("web", m["configured_type"]);
  TEST_ASSERT_EQUAL_STRING("v2.19.0", m["version"]);
  // Halyard's build, not upstream's latest: known without a check.
  TEST_ASSERT_EQUAL_STRING("v2.19.0-halyard.1", m["remote_version"]);
  TEST_ASSERT_EQUAL(0, m["warnings"].size());

  call("machine.update.status", "{\"refresh\":true}");  // "check for updates"
  TEST_ASSERT_EQUAL(1, checks);
  svc.update_checked("cannot reach 192.168.1.20");  // the source did not answer: said, not hidden
  auto refreshed = notes("notify_update_refreshed");
  TEST_ASSERT_EQUAL(1, refreshed.size());
  JsonObject rm = refreshed[0]["params"][0]["version_info"]["mainsail"];
  TEST_ASSERT_EQUAL_STRING("v2.19.0-halyard.1", rm["remote_version"]);
  TEST_ASSERT_EQUAL(1, rm["warnings"].size());
  TEST_ASSERT_TRUE(rm["warnings"][0].as<std::string>().find("cannot reach 192.168.1.20") != std::string::npos);
  svc.update_checked("");  // it answers now
  TEST_ASSERT_EQUAL(0, call("machine.update.status", "{}")["result"]["version_info"]["mainsail"]["warnings"].size());

  // The update button.
  TEST_ASSERT_EQUAL_STRING("ok", call("machine.update.client", "{\"name\":\"mainsail\"}")["result"]);
  TEST_ASSERT_EQUAL(1, started.size());
  TEST_ASSERT_TRUE(call("machine.update.status", "{}")["result"]["busy"].as<bool>());
  TEST_ASSERT_EQUAL(409, call("machine.update.client", "{\"name\":\"mainsail\"}")["error"]["code"].as<int>());
  call("machine.update.status", "{\"refresh\":true}");
  TEST_ASSERT_EQUAL(1, checks);  // not while updating
  TEST_ASSERT_EQUAL(400, call("machine.update.client", "{\"name\":\"klipper\"}")["error"]["code"].as<int>());
  notes("");
  svc.update_progress("mainsail", "Downloading: 50%", false);
  installed = "v2.19.0-halyard.1";
  svc.update_progress("mainsail", "Installed Mainsail v2.19.0-halyard.1", true);
  auto progress = notes("notify_update_response");
  TEST_ASSERT_EQUAL(2, progress.size());
  TEST_ASSERT_EQUAL_STRING("mainsail", progress[0]["params"][0]["application"]);
  TEST_ASSERT_FALSE(progress[0]["params"][0]["complete"].as<bool>());
  TEST_ASSERT_TRUE(progress[1]["params"][0]["complete"].as<bool>());
  JsonDocument dd = call("machine.update.status", "{}");
  JsonObject done = dd["result"]["version_info"]["mainsail"];
  TEST_ASSERT_FALSE(call("machine.update.status", "{}")["result"]["busy"].as<bool>());
  TEST_ASSERT_EQUAL_STRING("v2.19.0-halyard.1", done["version"]);
}

