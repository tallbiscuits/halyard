// The commands after the last one starting with `first`, in the order the printer ran them.
static std::vector<std::string> executed_from(Rig& r, const std::string& first) {
  std::vector<std::string> out;
  for (auto& e : r.m.executed) {
    if (starts_with(e, first.c_str())) out.clear();
    out.push_back(e);
  }
  return out;
}

static bool has_command(Rig& r, const char* name) {
  JsonDocument d;
  return !query(r, d, "{\"gcode\":null}")["gcode"]["commands"][name].isNull();
}

static std::string homed(Rig& r) {
  JsonDocument d;
  return query(r, d, "{\"toolhead\":null}")["toolhead"]["homed_axes"].as<std::string>();
}

// Mainsail's jog and extrude buttons. Marlin moves an unhomed axis anywhere (into the
// frame), so Halyard refuses those moves, as Klipper does.
void test_toolhead_moves_and_homing() {
  Rig r;
  r.svc.ws_open(1);
  r.ready();
  JsonDocument d;
  const char* jog_z =
      "SAVE_GCODE_STATE NAME=_ui_movement\\nG91\\nG1 Z10 F600\\nRESTORE_GCODE_STATE NAME=_ui_movement";
  TEST_ASSERT_EQUAL_STRING("", homed(r).c_str());
  // Unhomed: the whole script is refused before any of it is sent, so no G91 is left behind.
  JsonDocument e = r.call(1, "printer.gcode.script", script(jog_z));
  TEST_ASSERT_EQUAL(400, e["error"]["code"].as<int>());
  TEST_ASSERT_TRUE(starts_with(e["error"]["message"].as<std::string>(), "Must home axis first: Z"));
  TEST_ASSERT_EQUAL(0, r.count_executed("G91"));
  e = r.call(1, "printer.gcode.script", script("G1 X10 Y5"));
  TEST_ASSERT_TRUE(starts_with(e["error"]["message"].as<std::string>(), "Must home axis first: XY"));
  e = r.call(1, "printer.gcode.script", script("G2 I5 J0"));  // an arc moves X and Y unnamed
  TEST_ASSERT_TRUE(starts_with(e["error"]["message"].as<std::string>(), "Must home axis first: XY"));
  TEST_ASSERT_EQUAL(0, r.count_executed("G1 X"));
  TEST_ASSERT_EQUAL(0, r.count_executed("G2"));
  // The extruder needs no homing; nor does a move after a G28 in the same script, though
  // the lines go out together.
  r.result(1, "printer.gcode.script", script("G1 E1 F300"));
  TEST_ASSERT_EQUAL(1, r.count_executed("G1 E1"));
  e = r.call(1, "printer.gcode.script", script("G28 X\\nG1 X10\\nG1 Y10"));
  TEST_ASSERT_TRUE(starts_with(e["error"]["message"].as<std::string>(), "Must home axis first: Y"));
  TEST_ASSERT_EQUAL(0, r.count_executed("G28"));
  r.result(1, "printer.gcode.script", script("G28 X\\nG1 X10"));
  TEST_ASSERT_EQUAL(1, r.count_executed("G1 X10"));
  TEST_ASSERT_EQUAL_STRING("x", homed(r).c_str());
  // G28 homes what it names, or everything; then the jog runs.
  r.result(1, "printer.gcode.script", script("G28 X Y"));
  TEST_ASSERT_EQUAL_STRING("xy", homed(r).c_str());
  r.result(1, "printer.gcode.script", script("G28"));
  TEST_ASSERT_EQUAL_STRING("xyz", homed(r).c_str());
  r.result(1, "printer.gcode.script", script(jog_z));
  std::vector<std::string> ran = executed_from(r, "G91");
  TEST_ASSERT_EQUAL(4, ran.size());
  TEST_ASSERT_EQUAL_STRING("G1 Z10 F600", ran[1].c_str());
  TEST_ASSERT_EQUAL_STRING("G90", ran[2].c_str());
  TEST_ASSERT_EQUAL_STRING("M82", ran[3].c_str());
  // The position, from M114 once the script is done (the fake homes Z to 10).
  TEST_ASSERT_TRUE(r.run_until([&] {
    return query(r, d, "{\"toolhead\":[\"position\"]}")["toolhead"]["position"][2].as<double>() == 10;
  }, 2000));
  TEST_ASSERT_EQUAL(10, query(r, d, "{\"gcode_move\":null}")["gcode_move"]["gcode_position"][2].as<double>());
  // Steppers switched off may be moved by hand: M84 forgets the axes it names, or all.
  r.result(1, "printer.gcode.script", script("M84 X"));
  TEST_ASSERT_EQUAL_STRING("yz", homed(r).c_str());
  r.result(1, "printer.gcode.script", script("M18 E"));
  TEST_ASSERT_EQUAL_STRING("yz", homed(r).c_str());
  r.result(1, "printer.gcode.script", script("M84"));
  TEST_ASSERT_EQUAL_STRING("", homed(r).c_str());
  // Marlin's idle timeout switches them off silently: 120 s after the last move, unless
  // M84 S changed it (which switches nothing off).
  r.result(1, "printer.gcode.script", script("G28"));
  uint32_t homed_at = r.now;
  TEST_ASSERT_TRUE(r.run_until([&] { return homed(r).empty(); }, 125000));
  TEST_ASSERT_UINT32_WITHIN(1000, 120000, r.now - homed_at);
  r.result(1, "printer.gcode.script", script("G28\\nM84 S300"));
  TEST_ASSERT_EQUAL_STRING("xyz", homed(r).c_str());
  r.run_until([] { return false; }, 200000);
  r.result(1, "printer.gcode.script", script("G1 X20"));  // a move starts the clock again
  r.run_until([] { return false; }, 200000);
  TEST_ASSERT_EQUAL_STRING("xyz", homed(r).c_str());
  TEST_ASSERT_TRUE(r.run_until([&] { return homed(r).empty(); }, 101000));
  // M109 and M190 keep the steppers on while they wait, however long the heating takes.
  r.result(1, "printer.gcode.script", script("M84 S120\\nG28"));
  r.m.heat_ms = 150000;  // longer than call() waits for its reply
  r.svc.ws_message(1, "{\"jsonrpc\":\"2.0\",\"method\":\"printer.gcode.script\",\"params\":" +
                          script("M109 S200") + ",\"id\":999}");
  TEST_ASSERT_TRUE(r.run_until([&] { return r.m.busy_until && r.now > r.m.busy_until + 1000; }, 155000));
  TEST_ASSERT_EQUAL_STRING("xyz", homed(r).c_str());
  r.result(1, "printer.gcode.script", script("M104 S0"));
  // A new connection forgets it: the printer may have restarted, with its own timeout.
  r.result(1, "printer.gcode.script", script("G28"));
  r.m.reboot();
  TEST_ASSERT_TRUE(r.run_until([&] { return r.link.state() != LinkState::Ready; }, 5000));
  r.ready();
  TEST_ASSERT_EQUAL_STRING("", query(r, d, "{\"toolhead\":null}")["toolhead"]["homed_axes"]);
  r.result(1, "printer.gcode.script", script("M84 S0"));  // no timeout
  r.result(1, "printer.gcode.script", script("G28"));
  r.run_until([] { return false; }, 130000);
  TEST_ASSERT_EQUAL_STRING("xyz", homed(r).c_str());

  // Not during a print, not even paused: RESTORE would change the job's own modes.
  Form f;
  TEST_ASSERT_EQUAL(201, r.upload(false, f.type(), f.file("job.gcode", harmless_job(5)).done()).status);
  r.result(1, "printer.print.start", "{\"filename\":\"job.gcode\"}");
  TEST_ASSERT_TRUE(r.run_until([&] { return r.printer.status().job == Job::Printing; }, 120000));
  TEST_ASSERT_EQUAL_STRING("xyz", query(r, d, "{\"toolhead\":null}")["toolhead"]["homed_axes"]);
  size_t g91 = r.count_executed("G91");
  e = r.call(1, "printer.gcode.script",
             script("SAVE_GCODE_STATE NAME=_ui_extrude\\nM83\\nG1 E10 F300\\nRESTORE_GCODE_STATE NAME=_ui_extrude"));
  TEST_ASSERT_EQUAL(400, e["error"]["code"].as<int>());
  TEST_ASSERT_EQUAL(0, r.count_executed("M83"));
  TEST_ASSERT_EQUAL(g91, r.count_executed("G91"));
  // A finished print switches the steppers off (SD_FINISHED_RELEASECOMMAND).
  TEST_ASSERT_TRUE(r.run_until([&] { return r.printer.status().job == Job::Idle; }, 60000));
  r.run_until([] { return false; }, 300);
  TEST_ASSERT_EQUAL_STRING("", homed(r).c_str());
}

