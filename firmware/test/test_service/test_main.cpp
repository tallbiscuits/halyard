static std::string read_all(const std::string& path) {
  std::string out;
  if (FILE* f = fopen(path.c_str(), "rb")) {
    char buf[256];
    size_t n;
    while ((n = fread(buf, 1, sizeof buf, f)) > 0) out.append(buf, n);
    fclose(f);
  }
  return out;
}

static void write_all(const std::string& path, const std::string& text) {
  FILE* f = fopen(path.c_str(), "wb");
  TEST_ASSERT_NOT_NULL(f);
  fwrite(text.data(), 1, text.size(), f);
  fclose(f);
}

// A zip's entries by name, read back through its central directory (as unzip does), with each
// entry's data checked against its CRC. Empty if the archive is malformed.
static std::map<std::string, std::string> unzip(const std::string& z) {
  auto u16 = [&](size_t i) { return (uint32_t)(uint8_t)z[i] | (uint32_t)(uint8_t)z[i + 1] << 8; };
  auto u32 = [&](size_t i) { return u16(i) | u16(i + 2) << 16; };
  std::map<std::string, std::string> out;
  if (z.size() < 22 || u32(z.size() - 22) != 0x06054b50) return {};
  uint32_t n = u16(z.size() - 12), cd = u32(z.size() - 6);
  if (cd + u32(z.size() - 10) != z.size() - 22) return {};
  for (uint32_t i = 0; i < n; i++) {
    if (u32(cd) != 0x02014b50 || u16(cd + 10) != 0) return {};  // stored
    uint32_t crc = u32(cd + 16), size = u32(cd + 24), name_len = u16(cd + 28), local = u32(cd + 42);
    std::string name = z.substr(cd + 46, name_len);
    if (u32(local) != 0x04034b50 || z.substr(local + 30, u16(local + 26)) != name) return {};
    size_t data = local + 30 + u16(local + 26) + u16(local + 28);
    std::string body = z.substr(data, size);
    if (crc32(0, (const Bytef*)body.data(), body.size()) != crc) return {};
    if (u32(data + size) != 0x08074b50 || u32(data + size + 4) != crc) return {};  // descriptor
    out[name] = body;
    cd += 46 + name_len + u16(cd + 30) + u16(cd + 32);
  }
  return out;
}

static std::string read_zip(halyard::ZipStream& zip, size_t chunk) {
  std::string z;
  std::vector<uint8_t> buf(chunk);
  while (size_t n = zip.read(buf.data(), chunk)) z.append((const char*)buf.data(), n);
  return z;
}

// Mainsail downloads several files as one zip: server.files.zip, then a GET of its destination.
void test_download_several_files_as_zip() {
  Rig r;
  r.svc.ws_open(1);
  std::string a = harmless_job(3), b(70000, 'x');
  for (size_t i = 0; i < b.size(); i++) b[i] = (char)(i * 7 % 251);
  write_all(g_root + "/gcodes/Phone Stand.gcode", a);
  write_all(g_root + "/gcodes/\xC3\x85ngbåt.gcode", b);
  write_all(g_root + "/halyard.cfg", "[wifi]\nssid: Home\npassword: sesame-open\n");
  JsonDocument d = r.result(1, "server.files.zip",
      "{\"items\":[\"gcodes/Phone Stand.gcode\",\"gcodes/\xC3\x85ngbåt.gcode\",\"config/halyard.cfg\"],"
      "\"dest\":\"config/gcodes-20260929-230000.zip\"}");
  TEST_ASSERT_EQUAL_STRING("config", d["result"]["destination"]["root"]);
  TEST_ASSERT_EQUAL_STRING("gcodes-20260929-230000.zip", d["result"]["destination"]["path"]);
  TEST_ASSERT_EQUAL_STRING("zip_files", d["result"]["action"]);
  // Nothing was written to the card; the archive is made as it downloads.
  TEST_ASSERT_EQUAL_STRING("", r.svc.download_path("config/gcodes-20260929-230000.zip").c_str());
  TEST_ASSERT_NULL(r.svc.zip_download("config/other.zip").get());
  for (size_t chunk : {7, 8192}) {
    auto zip = r.svc.zip_download("config/gcodes-20260929-230000.zip");
    TEST_ASSERT_NOT_NULL(zip.get());
    auto files = unzip(read_zip(*zip, chunk));
    TEST_ASSERT_FALSE(zip->failed());
    TEST_ASSERT_EQUAL(3, files.size());
    TEST_ASSERT_TRUE(files["Phone Stand.gcode"] == a);
    TEST_ASSERT_TRUE(files["\xC3\x85ngbåt.gcode"] == b);
    TEST_ASSERT_EQUAL_STRING("[wifi]\nssid: Home\npassword: ********\n", files["halyard.cfg"].c_str());
  }
  // A file deleted before the download fails it, rather than giving a zip without it.
  auto zip = r.svc.zip_download("config/gcodes-20260929-230000.zip");
  unlink((g_root + "/gcodes/Phone Stand.gcode").c_str());
  read_zip(*zip, 8192);
  TEST_ASSERT_TRUE(zip->failed());
  // Only files that are there, and only into a root.
  TEST_ASSERT_EQUAL(404, r.call(1, "server.files.zip", "{\"items\":[\"gcodes/Phone Stand.gcode\"]}")["error"]["code"]);
  TEST_ASSERT_EQUAL(404, r.call(1, "server.files.zip", "{\"items\":[\"gcodes/../halyard.cfg\"]}")["error"]["code"]);
  TEST_ASSERT_EQUAL(400, r.call(1, "server.files.zip", "{\"items\":[]}")["error"]["code"]);
  TEST_ASSERT_EQUAL(400, r.call(1, "server.files.zip",
      "{\"items\":[\"config/halyard.cfg\"],\"dest\":\"config/../x.zip\"}")["error"]["code"]);
  // Without a destination, one is named as Moonraker names it.
  d = r.result(1, "server.files.zip", "{\"items\":[\"config/halyard.cfg\"]}");
  TEST_ASSERT_EQUAL_STRING("collection-1790000000.zip", d["result"]["destination"]["path"]);
}

