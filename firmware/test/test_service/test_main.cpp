void test_mainsail_upload_then_batched_metadata() {
  Rig r;
  r.svc.ws_open(1);
  r.ready();
  Form f;
  std::string body = f.file("Phone Stand.gcode", with_thumbnail(harmless_job(3, 210, 55)))
                         .field("root", "gcodes").done();
  HttpResponse res = r.upload(false, f.type(), body, 333);
  TEST_ASSERT_EQUAL_MESSAGE(201, res.status, res.body.c_str());
  JsonDocument d = parse(res.body);
  TEST_ASSERT_EQUAL_STRING("Phone Stand.gcode", d["item"]["path"]);
  TEST_ASSERT_EQUAL_STRING("create_file", d["action"]);
  TEST_ASSERT_FALSE(d["print_started"].as<bool>());
  auto changed = r.notes(1, "notify_filelist_changed");  // marlin.cfg's, on connecting, aside
  changed.erase(std::remove_if(changed.begin(), changed.end(), [](JsonDocument& n) {
    return n["params"][0]["item"]["root"] != "gcodes";
  }), changed.end());
  TEST_ASSERT_EQUAL(1, changed.size());
  TEST_ASSERT_EQUAL_STRING("create_file", changed[0]["params"][0]["action"]);
  // Mainsail then asks for the metadata in a batch.
  JsonDocument b = parse(r.svc.ws_message(1,
      "[{\"jsonrpc\":\"2.0\",\"method\":\"server.files.metadata\",\"params\":"
      "{\"filename\":\"Phone Stand.gcode\"},\"id\":25}]"));
  JsonObject m = b[0]["result"];
  TEST_ASSERT_EQUAL_FLOAT(3, m["estimated_time"].as<float>());
  TEST_ASSERT_EQUAL_FLOAT(210, m["first_layer_extr_temp"].as<float>());
  TEST_ASSERT_EQUAL_STRING("PrusaSlicer", m["slicer"]);
  TEST_ASSERT_EQUAL_STRING(".thumbs/Phone Stand-16x16.png", m["thumbnails"][0]["relative_path"]);
  // The thumbnail downloads under the URL Mainsail builds, and nothing outside the library does.
  std::string thumb = r.svc.download_path("gcodes/.thumbs/Phone%20Stand-16x16.png");
  TEST_ASSERT_EQUAL_STRING((g_root + "/gcodes/.thumbs/Phone Stand-16x16.png").c_str(), thumb.c_str());
  TEST_ASSERT_TRUE(r.svc.download_path("gcodes/Phone%20Stand.gcode").size() > 0);
  TEST_ASSERT_EQUAL(0, r.svc.download_path("gcodes/../database.json").size());
  TEST_ASSERT_EQUAL(0, r.svc.download_path("gcodes/.meta/Phone Stand.gcode.meta").size());
  TEST_ASSERT_EQUAL(0, r.svc.download_path("config/.theme/default.json").size());
  // A browser saves a download rather than showing it, under the library name.
  TEST_ASSERT_EQUAL_STRING("attachment; filename=\"Phone Stand.gcode\"; "
                           "filename*=UTF-8''Phone%20Stand.gcode",
                           Service::content_disposition(
                               r.svc.download_path("gcodes/Phone%20Stand.gcode")).c_str());
  TEST_ASSERT_EQUAL_STRING("attachment; filename=\"__l _x_.gcode\"; "
                           "filename*=UTF-8''%C3%85l%20%22x%22.gcode",
                           Service::content_disposition("gcodes/\xC3\x85l \"x\".gcode").c_str());
  // The file list, with metadata when asked.
  JsonDocument dir = r.result(1, "server.files.get_directory", "{\"path\":\"gcodes\",\"extended\":true}");
  TEST_ASSERT_EQUAL(1, dir["result"]["files"].size());
  TEST_ASSERT_EQUAL_STRING("Phone Stand.gcode", dir["result"]["files"][0]["filename"]);
  TEST_ASSERT_EQUAL_FLOAT(3, dir["result"]["files"][0]["estimated_time"].as<float>());
  TEST_ASSERT_EQUAL(1, r.result(1, "server.files.list")["result"].size());
}

