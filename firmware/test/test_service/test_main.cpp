  TEST_ASSERT_EQUAL(404, r.call(1, "server.files.metadata", "{\"filename\":\"a.gcode\"}")["error"]["code"].as<int>());
  // Folders do not exist in the library.
  TEST_ASSERT_EQUAL(400, r.call(1, "server.files.post_directory", "{\"path\":\"gcodes/new\"}")["error"]["code"].as<int>());
  // Delete over HTTP, as Mainsail's file manager does it.
